// Package original CC-BY-3.0 scan bytes. See ATTRIBUTIONS.md for attribution.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const folder = root + "assets/head-scan/";
const bytes = await readFile(folder + "LeePerrySmith.glb");
const colour = await readFile(folder + "Map-COL.jpg");
const normal = await readFile(
  folder + "Infinite-Level_02_Tangent_SmoothUV.jpg",
);
const meta = {
  name: "Infinite, 3D Head Scan",
  author: "Lee Perry-Smith",
  studio: "Infinite-Realities",
  originalWork: "Triplegangers",
  license: "CC-BY-3.0",
  licenseUrl: "https://creativecommons.org/licenses/by/3.0/",
  source:
    "https://github.com/mrdoob/three.js/tree/2bd920c3a604a3b847d9187b0a1c21e33807ecb3/examples/models/gltf/LeePerrySmith",
  originalUrl: "http://www.triplegangers.com/",
  credit:
    "Infinite, 3D Head Scan by Lee Perry-Smith / Infinite-Realities, based on Triplegangers. CC BY 3.0. Adapted for this game.",
  changes:
    "Placement, scaling and integration into procedural characters; material settings adapted. Original GLB and JPEG bytes retained.",
};
const source =
  "// Generated by scripts/pack-head-scan.mjs. Original scan: Lee Perry-Smith, CC BY 3.0.\n" +
  "export const SCAN_HEAD_GLB=Uint8Array.from(atob(" +
  JSON.stringify(bytes.toString("base64")) +
  "),character=>character.charCodeAt(0));\n" +
  "export const SCAN_HEAD_COLOR=" +
  JSON.stringify("data:image/jpeg;base64," + colour.toString("base64")) +
  ";\n" +
  "export const SCAN_HEAD_NORMAL=" +
  JSON.stringify("data:image/jpeg;base64," + normal.toString("base64")) +
  ";\n" +
  "export const SCAN_HEAD_META=Object.freeze(" +
  JSON.stringify(meta) +
  ");\n";
await writeFile(root + "src/head-scan-data.js", source);
console.log(
  "Packed original CC-BY-3.0 head scan (" +
    Math.round(source.length / 1024) +
    " KB).",
);
