// Repack Blender's CC0 human output for a synchronous, offline-friendly factory.
// Usage: node scripts/pack-human-asset.mjs /tmp/human-v9
import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const input = process.argv[2];
if (!input) throw Error("Supply the output folder from export-human-asset.py");
const source = JSON.parse(
  await readFile(path.join(input, "human.json"), "utf8"),
);
const manifestPath = path.join(root, "assets/human-v9/manifest.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const chunks = [];
let total = 0;
function append(values) {
  const pad = (4 - (total % 4)) % 4;
  if (pad) {
    chunks.push(Buffer.alloc(pad));
    total += pad;
  }
  const offset = total;
  const buffer = Buffer.from(
    values.buffer,
    values.byteOffset,
    values.byteLength,
  );
  chunks.push(buffer);
  total += buffer.length;
  return { offset, length: values.length };
}
function quantize(values, size, kind = "range") {
  const low = Array(size).fill(Infinity),
    high = Array(size).fill(-Infinity);
  for (let i = 0; i < values.length; i++) {
    const c = i % size;
    low[c] = Math.min(low[c], values[i]);
    high[c] = Math.max(high[c], values[i]);
  }
  const packed =
    kind === "normal"
      ? new Int16Array(values.length)
      : new Uint16Array(values.length);
  for (let i = 0; i < values.length; i++) {
    const c = i % size;
    packed[i] =
      kind === "normal"
        ? Math.round(Math.max(-1, Math.min(1, values[i])) * 32767)
        : Math.round(
            ((values[i] - low[c]) / Math.max(1e-12, high[c] - low[c])) * 65535,
          );
  }
  return { ...append(packed), size, low, high, kind };
}
const images = [],
  imageNames = [],
  materials = {};
for (const [name, material] of Object.entries(source.materials)) {
  materials[name] = { ...material };
  for (const channel of ["map", "normalMap", "aoMap"]) {
    if (!material[channel]) continue;
    const filename = material[channel];
    if (!imageNames.includes(filename)) {
      const raw = await readFile(path.join(input, filename));
      imageNames.push(filename);
      images.push(
        `data:image/${filename.endsWith(".png") ? "png" : filename.endsWith(".webp") ? "webp" : "jpeg"};base64,${raw.toString("base64")}`,
      );
    }
    materials[name][channel] = imageNames.indexOf(filename);
  }
}
const variants = {};
for (const [name, variant] of Object.entries(source.variants)) {
  let triangles = 0,
    vertices = 0;
  const parts = variant.parts.map((part) => {
    vertices += part.position.length / 3;
    triangles += part.indices.length / 3;
    const Type = part.position.length / 3 < 65536 ? Uint16Array : Uint32Array;
    return {
      name: part.name,
      material: part.material,
      position: quantize(part.position, 3),
      normal: quantize(part.normal, 3, "normal"),
      uv: quantize(part.uv, 2),
      skinIndex: { ...append(Uint8Array.from(part.skinIndex)), size: 4 },
      skinWeight: quantize(part.skinWeight, 4),
      indices: {
        ...append(Type.from(part.indices)),
        type: Type === Uint32Array ? "u32" : "u16",
      },
    };
  });
  variants[name] = {
    bones: variant.bones,
    support: variant.support,
    parts,
    height: variant.height,
    triangles,
    vertices,
  };
}
const binary = gzipSync(Buffer.concat(chunks), { level: 9 });
const metadata = {
  name: "MakeHuman CC0 workers and citizens",
  author: manifest.author,
  license: "CC0-1.0",
  source: manifest.sources.officialIndex,
  materials,
  variants,
  imageNames,
  geometrySHA256: createHash("sha256").update(binary).digest("hex"),
};
await writeFile(
  path.join(root, "src/human-asset-data.js"),
  `// Generated by scripts/pack-human-asset.mjs; MakeHuman core assets CC0.\nexport const HUMAN_META = ${JSON.stringify(metadata)};\nexport const HUMAN_GEOMETRY = Uint8Array.from(atob(${JSON.stringify(binary.toString("base64"))}), c => c.charCodeAt(0));\nexport const HUMAN_IMAGES = ${JSON.stringify(images)};\n`,
);
const derived = path.join(root, "assets/human-v9/derived");
await mkdir(derived, { recursive: true });
await writeFile(path.join(derived, "human-geometry.bin.gz"), binary);
for (const name of imageNames)
  await copyFile(path.join(input, name), path.join(derived, name));
manifest.derived = {
  generator: "scripts/export-human-asset.py",
  packer: "scripts/pack-human-asset.mjs",
  sourceJSONSHA256: createHash("sha256")
    .update(await readFile(path.join(input, "human.json")))
    .digest("hex"),
  geometrySHA256: metadata.geometrySHA256,
  variants: Object.fromEntries(
    Object.entries(variants).map(([key, value]) => [
      key,
      {
        triangles: value.triangles,
        vertices: value.vertices,
        height: value.height,
      },
    ]),
  ),
  imageNames,
};
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
console.log(
  JSON.stringify(
    {
      geometryBytes: binary.length,
      moduleBytes: (await readFile(path.join(root, "src/human-asset-data.js")))
        .length,
      variants: manifest.derived.variants,
    },
    null,
    2,
  ),
);
